    /**
     * @param array<string,mixed> $d Observability::collect()
     * @param array<string,string> $stamp Observability::stamp()
     * @return array{tex:string,assets:array}
     */
    public static function report(array $d, array $stamp, string $lang = 'fr'): array
    {
        $en = $lang === 'en';
        $W = self::W[$en ? 'en' : 'fr'];
        $e = fn($s) => ExportTheme::esc((string)$s);
        $fmt = fn($ymd) => date('d/m/Y', strtotime((string)$ymd));
        $fdt = fn($ts) => date('d/m/Y H:i', strtotime((string)$ts));
        $n = fn($v) => number_format((int)$v, 0, ',', ' ');
        $S = $d['summary'];

        $filter = $d['filters']['category'] ? self::catLabel((string)$d['filters']['category'], $en) : $W['all'];
        if ($d['filters']['q'] !== '') {
            $filter .= ' · « ' . $d['filters']['q'] . ' »';
        }
        $body = ExportTheme::titleBlock($W['kind'], $fmt($d['period']['from']) . ' – ' . $fmt($d['period']['to']), '', [
            [$W['ref'], $stamp['id']], [$W['filter'], $filter], [$W['by'], $stamp['generated_by']], [$W['on'], $fdt($stamp['generated_at'])],
        ]);

        $body .= ExportTheme::statCards([
            [$n($S['events']), $W['events']], [$n($S['actors']), $W['actors']],
            [$n($S['logins_ok']), $W['logins']], [$n($S['logins_failed']) . ' (' . str_replace('.', ',', (string)$S['failure_rate']) . ' %)', $W['failed']],
        ]);
        $body .= ExportTheme::statCards([
            [$n($S['security']), $W['security']], [$n($S['exports']), $W['exports']],
            [$n($S['deletions']), $W['deletions']], [$n($S['verifications']) . ($S['verify_suspect'] > 0 ? ' (' . $n($S['verify_suspect']) . '!)' : ''), $W['verifs']],
        ]);

        // Activity chart: per day up to 45 days, per week beyond
        $tl = $d['timeline'];
        $weekly = count($tl) > 45;
        if ($weekly) {
            $agg = [];
            foreach ($tl as $r) {
                $k = date('o-\WW', strtotime($r['day']));
                $agg[$k] ??= ['label' => $fmt($r['day']), 'events' => 0, 'failed' => 0];
                $agg[$k]['events'] += $r['events'];
                $agg[$k]['failed'] += $r['failed'];
            }
            $series = array_values($agg);
        } else {
            $series = array_map(fn($r) => ['label' => $fmt($r['day']), 'events' => $r['events'], 'failed' => $r['failed']], $tl);
        }
        // runs of three or more quiet days become one line
        $folded = [];
        for ($i = 0, $c = count($series); $i < $c; $i++) {
            $j = $i;
            while ($j < $c && $series[$j]['events'] === 0) {
                $j++;
            }
            if ($j - $i >= 3 && !$weekly) {
                $folded[] = ['label' => $series[$i]['label'] . ' – ' . $series[$j - 1]['label'], 'events' => 0, 'failed' => 0, 'quiet' => $j - $i];
                $i = $j - 1;
            } else {
                $folded[] = $series[$i];
            }
        }
        $series = $folded;
        $max = max(1, ...array_map(fn($r) => (int)$r['events'], $series ?: [['events' => 1]]));
        $body .= '\\section*{' . $e($weekly ? $W['weekly'] : $W['daily']) . "}\n{\\small\\color{svgray}" . $e($W['daily_note']) . "}\\par\\vspace{0.3em}\n";
        $body .= "{\\footnotesize\\renewcommand{\\arraystretch}{0.92}\\noindent\\begin{tabular}{@{}r@{\\hspace{0.7em}}l@{\\hspace{0.6em}}l@{}}\n";
        foreach ($series as $r) {
            $w = round($r['events'] / $max * 105, 1);
            $body .= $e($r['label']) . ' & ' . ($w > 0 ? "\\textcolor{svclay}{\\rule{{$w}mm}{2.2mm}}" : '\\rule{0pt}{2.2mm}') . ' & '
                . (int)$r['events'] . (isset($r['quiet']) ? ' {\\color{svgray}(' . $e(strtr($W['quiet'], [':n' => (string)$r['quiet']])) . ')}' : ($r['failed'] > 0 ? ' {\\color{svgray}(' . (int)$r['failed'] . ')}' : '')) . " \\\\\n";
        }
        $body .= "\\end{tabular}}\\par\n";

        // Rankings
        $body .= '\\section*{' . $e($W['top_actions']) . "}\n";
        $maxA = max(1, ...array_values($d['top_actions'] ?: [1]));
        $rows = [];
        foreach ($d['top_actions'] as $a => $c) {
            $rows[] = [$e(Observability::label((string)$a)), ExportTheme::miniBar($c / $maxA * 100, 40.0, 'svclay'), (string)(int)$c];
        }
        $body .= $rows ? ExportTheme::table([[$W['action'], 'p{6.4cm}'], ['', 'l'], [$W['count'], 'r']], $rows) : '\\textit{' . $e($W['none']) . "}\n";

        $body .= '\\section*{' . $e($W['top_actors']) . "}\n";
        $rows = [];
        foreach ($d['top_actors'] as $r) {
            $anon = $r['name'] === '—';
            $rows[] = [$e($anon ? $W['anon'] : $r['name']), $e($anon ? '' : $r['role']), $e($fdt($r['last_seen'])), (string)(int)$r['c']];
        }
        $body .= $rows ? ExportTheme::table([[$W['name'], 'p{6cm}'], [$W['role'], 'l'], [$W['last'], 'l'], [$W['count'], 'r']], $rows) : '\\textit{' . $e($W['none']) . "}\n";

        // Security
        $body .= '\\section*{' . $e($W['sec_h']) . "}\n";
        $body .= '{\\small\\color{svgray}' . $e($W['rate_note']) . ' : \\textbf{' . $e(str_replace('.', ',', (string)$S['failure_rate'])) . "\\,\\%}}\\par\\vspace{0.4em}\n";
        $body .= '\\textbf{' . $e($W['ips']) . "}\\par\\vspace{0.2em}\n";
        $rows = [];
        foreach ($d['failed_ips'] as $r) {
            $rows[] = [$e($r['ip'] ?: '—'), (string)(int)$r['c'], $e($fdt($r['last_seen']))];
        }
        $body .= $rows ? ExportTheme::table([[$W['ip'], 'p{5cm}'], [$W['count'], 'r'], [$W['last'], 'r']], $rows) : '\\textit{' . $e($W['none']) . "}\\par\n";

        $body .= '\\vspace{0.6em}\\textbf{' . $e($W['sec_events']) . "}\\par\\vspace{0.2em}\n";
        $rows = [];
        foreach (array_slice($d['security_events'], 0, 60) as $r) {
            $rows[] = [$e($fdt($r['created_at'])), $e($r['name'] === '—' ? $W['anon'] : $r['name']), $e(Observability::label((string)$r['action'])), $e(mb_substr((string)$r['details'], 0, 110)), $e((string)$r['ip_address'])];
        }
        $body .= $rows ? ExportTheme::table([[$W['date'], 'l'], [$W['author'], '>{\\raggedright\\arraybackslash}p{2.6cm}'], [$W['action'], '>{\\raggedright\\arraybackslash}p{2.9cm}'], [$W['details'], '>{\\raggedright\\arraybackslash}p{4.4cm}'], ['IP', 'l']], $rows) : '\\textit{' . $e($W['none']) . "}\\par\n";

        // Delivery and traffic
        $body .= '\\section*{' . $e($W['delivery']) . "}\n";
        $rows = [];
        foreach ($d['delivery'] as $k => $r) {
            $rows[] = [$e($W['ch'][$k] ?? $k), (string)$r['total'], (string)$r['sent'], (string)$r['failed'], (string)$r['pending'],
                $r['success_rate'] === null ? '---' : $e(str_replace('.', ',', (string)$r['success_rate'])) . '\\,\\%'];
        }
        $body .= ExportTheme::table([[$W['channel'], 'p{5.4cm}'], [$W['total'], 'r'], [$W['sent'], 'r'], [$W['failedm'], 'r'], [$W['pending'], 'r'], [$W['rate'], 'r']], $rows);
        if ($d['usage']) {
            $body .= '\\section*{' . $e($W['usage']) . "}\n";
            $rows = array_map(fn($r) => [$e($r['event']), (string)$r['count']], $d['usage']);
            $body .= ExportTheme::table([[$W['event'], 'p{8cm}'], [$W['count'], 'r']], $rows);
        }

        // Integrity
        $fp = strtoupper(implode('-', str_split(substr($stamp['fingerprint'], 0, 24), 4)));
        $body .= "\\par\\needspace{6cm}\\vspace{1em}\\noindent{\\setlength{\\fboxsep}{10pt}\\colorbox{svcard}{\\begin{minipage}{\\dimexpr\\textwidth-20pt\\relax}\n"
            . '{\\sffamily\\bfseries\\color{svclay}' . $e($W['integrity']) . "}\\par\\vspace{3pt}\n"
            . '{\\small ' . $e(strtr($W['integrity_p'], [':a' => (string)$d['retention']['audit_days'], ':l' => (string)$d['retention']['login_attempts_days']])) . "}\\par\\vspace{5pt}\n"
            . '{\\scriptsize\\sffamily\\color{svgray}\\textbf{' . $e($W['ref']) . '} \\ {\\ttfamily ' . preg_replace('/[^A-Z0-9-]/', '', $stamp['id']) . '}\\quad\\textbf{' . $e($W['fingerprint']) . '} \\ {\\ttfamily ' . $fp . "}}\n"
            . "\\end{minipage}}}\\par\n";

        // Appendix: the log
        $rows = [];
        foreach ($d['rows'] as $r) {
            $rows[] = [$e($fdt($r['created_at'])), $e($r['name'] !== '' ? $r['name'] : $W['anon']), $e(Observability::label((string)$r['action'])), $e(mb_substr((string)$r['details'], 0, 140)), $e($r['ip'])];
        }
        $body .= '\\clearpage\\section*{' . $e($W['log_h']) . "}\n{\\small\\color{svgray}"
            . $e($d['rows_truncated'] ? strtr($W['log_note'], [':n' => (string)count($d['rows']), ':t' => $n($d['rows_total'])]) : strtr($W['log_all'], [':t' => $n($d['rows_total'])]))
            . "}\\par\\vspace{0.3em}\n";
        $body .= $rows ? '{\\scriptsize' . ExportTheme::table([[$W['date'], 'l'], [$W['author'], '>{\\raggedright\\arraybackslash}p{2.7cm}'], [$W['action'], '>{\\raggedright\\arraybackslash}p{3.1cm}'], [$W['details'], '>{\\raggedright\\arraybackslash}p{5.6cm}'], ['IP', 'l']], $rows) . '}'
            : '\\textit{' . $e($W['none']) . "}\n";

        return ['tex' => ExportTheme::document($body, [
            'lang' => $lang, 'title' => $W['kind'] . ' ' . $stamp['id'],
            'header_left' => $W['header'], 'header_right' => $fmt($d['period']['from']) . ' – ' . $fmt($d['period']['to']),
            'footer_left' => 'StudyVibe · ' . $stamp['id'],
        ]), 'assets' => []];
    }

    public static function catLabel(string $category, bool $en): string
    {
        $map = [
            'security' => ['Sécurité', 'Security'], 'access' => ['Accès et comptes', 'Access and accounts'], 'academic' => ['Activité pédagogique', 'Academic activity'],
            'exports' => ['Exports', 'Exports'], 'verification' => ['Vérification de documents', 'Document verification'],
        ];
        return ($map[$category] ?? [$category, $category])[$en ? 1 : 0];
    }
}
